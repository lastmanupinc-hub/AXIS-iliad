#!/usr/bin/env node
// Generate the trust-fabric attestation bundle from THIS REPOSITORY'S REAL FILES.
//
// WHY THIS EXISTS. The committed bundle asserted integrity over bytes that no
// longer matched: `generated_at: 1970-01-01`, 5 of 9 leaf digests disagreeing
// with the files they named, and one leaf (packaging/manifests/npm-package.json)
// attesting a file that does not exist. It shipped attached to every GitHub
// Release regardless, because the release step only ran `test -f` on it.
//
// Two things had to be true for that to persist:
//   1. `make attest` was a no-op — literally `@echo "Attestation bundle: ..."`.
//      Nothing ever regenerated the file, so it aged out of truth in place.
//   2. The bundle's leaves came from generator-core's `closerAttestedArtifacts`,
//      which hashes what the CLOSER PROGRAM GENERATES FOR A TARGET PROJECT — not
//      what this repository ships — while the leaf paths read like repo paths.
//      The 4 that matched did so only because the closer's output for them
//      happened to be committed verbatim.
//
// So "regenerate at ship time" was NOT the fix on its own (it would have kept
// attesting generated content under repo-looking paths). This script implements
// the actual remedy: re-point the attestation at the repo's real files and
// compute it from them, at ship time, every time.
//
// The recipe is unchanged from the bundle's own stated formula, so
// scripts/verify-attestation.mjs validates this output without modification:
//   leaf   = sha256(path + "\n" + bytes)   [CRLF normalized to LF]
//   tree   = pairwise sha256(left + right), last node duplicated when odd
//   sig    = sha256(certlib_profile + ":" + merkle_root)
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const sha256 = (s) => createHash("sha256").update(s).digest("hex");
const rel = (p) => new URL(`../${p}`, import.meta.url);

// What this repository actually ships as build/configuration surface. Kept as an
// explicit list rather than a glob: an attestation should cover a deliberate set
// somebody chose, and a glob would silently change what is attested whenever a
// file appears or disappears — which is the failure mode this replaces.
const ATTESTED = [
  "packaging/LICENSE",
  "Dockerfile",
  "docker-compose.yml",
  ".github/workflows/ci.yml",
  ".github/workflows/release.yml",
  ".github/workflows/reusable-test-suite.yml",
  "packaging/manifests/unreal.uplugin",
  "packaging/manifests/vscode-extension.json",
  "Makefile",
];

const missing = ATTESTED.filter((p) => !existsSync(rel(p)));
if (missing.length > 0) {
  // Fail rather than silently attest a shorter set. A leaf naming a file that
  // does not exist is exactly the defect that made the old bundle false.
  console.error("Refusing to generate an attestation: these attested paths do not exist:\n");
  for (const m of missing) console.error(`  - ${m}`);
  console.error("\nUpdate ATTESTED in scripts/generate-attestation.mjs to match what this repo ships.");
  process.exit(1);
}

const leaves = ATTESTED.map((path) => ({
  path,
  digest: sha256(`${path}\n${readFileSync(rel(path), "utf8").replace(/\r\n/g, "\n")}`),
}));

// Merkle root over the leaf digests, pairwise, duplicating the last node on an
// odd level (the formula merkle-proof.json already documents).
const levels = [leaves.map((l) => l.digest)];
while (levels[levels.length - 1].length > 1) {
  const cur = levels[levels.length - 1];
  const next = [];
  for (let i = 0; i < cur.length; i += 2) next.push(sha256(`${cur[i]}${cur[i + 1] ?? cur[i]}`));
  levels.push(next);
}
const merkleRoot = levels[levels.length - 1][0];

const CERTLIB_PROFILE = "certlib-offline-v1";

// Deterministic ids derived from the content itself, so re-running on an
// unchanged tree produces an unchanged bundle apart from generated_at.
const contentId = sha256(leaves.map((l) => l.digest).join(""));

const attestation = {
  schema_version: "1.0",
  certlib_profile: CERTLIB_PROFILE,
  generated_at: new Date().toISOString(),
  snapshot_id: `repo-${contentId.slice(0, 32)}`,
  project_id: `repo-${sha256("axis-iliad").slice(0, 32)}`,
  product_name: "axis-iliad",
  package_root: "./",
  attests:
    "Build and configuration files that ship from THIS repository, hashed as committed " +
    "(line endings normalized to LF). Generated by scripts/generate-attestation.mjs during " +
    "`make attest`; verified by scripts/verify-attestation.mjs before any Release attaches it. " +
    "Markdown docs are excluded: the autonomy loop appends a footer to several after generation, " +
    "so their shipped bytes are not knowable here.",
  merkle_root: merkleRoot,
  signature: {
    algorithm: "sha256-pseudo-signature",
    signer: "axis-closer",
    value: sha256(`${CERTLIB_PROFILE}:${merkleRoot}`),
  },
  leaf_count: leaves.length,
  leaves,
};

const proof = { schema_version: "1.0", merkle_root: merkleRoot, levels };

writeFileSync(rel("packaging/trust-fabric/attestation.json"), `${JSON.stringify(attestation, null, 2)}\n`);
writeFileSync(rel("packaging/trust-fabric/merkle-proof.json"), `${JSON.stringify(proof, null, 2)}\n`);

console.log(`Attestation generated: ${leaves.length} leaves, root ${merkleRoot.slice(0, 12)}…`);
